CREATE TABLE roles (
    id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR2(50) NOT NULL UNIQUE
);

CREATE TABLE departments (
    id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR2(100) NOT NULL UNIQUE,
    code VARCHAR2(20) NOT NULL UNIQUE
);

CREATE TABLE users (
    id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username VARCHAR2(80) NOT NULL UNIQUE,
    email VARCHAR2(150) NOT NULL UNIQUE,
    password_hash VARCHAR2(100) NOT NULL,
    full_name VARCHAR2(150) NOT NULL,
    department_id NUMBER,
    enabled NUMBER(1) DEFAULT 1 NOT NULL,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT fk_users_dept FOREIGN KEY (department_id) REFERENCES departments (id)
);

CREATE TABLE user_roles (
    user_id NUMBER NOT NULL,
    role_id NUMBER NOT NULL,
    CONSTRAINT pk_user_roles PRIMARY KEY (user_id, role_id),
    CONSTRAINT fk_ur_user FOREIGN KEY (user_id) REFERENCES users (id),
    CONSTRAINT fk_ur_role FOREIGN KEY (role_id) REFERENCES roles (id)
);

CREATE TABLE complaint_categories (
    id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR2(100) NOT NULL UNIQUE,
    department_id NUMBER NOT NULL,
    CONSTRAINT fk_cat_dept FOREIGN KEY (department_id) REFERENCES departments (id)
);

CREATE SEQUENCE ticket_seq START WITH 1 INCREMENT BY 1 NOCACHE;

CREATE TABLE complaints (
    id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ticket_no VARCHAR2(30) NOT NULL UNIQUE,
    title VARCHAR2(200) NOT NULL,
    description CLOB,
    location VARCHAR2(300) NOT NULL,
    status VARCHAR2(30) NOT NULL,
    priority VARCHAR2(20) NOT NULL,
    category_id NUMBER NOT NULL,
    created_by NUMBER NOT NULL,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT fk_comp_cat FOREIGN KEY (category_id) REFERENCES complaint_categories (id),
    CONSTRAINT fk_comp_user FOREIGN KEY (created_by) REFERENCES users (id)
);

CREATE TABLE complaint_history (
    id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    complaint_id NUMBER NOT NULL,
    old_status VARCHAR2(30),
    new_status VARCHAR2(30) NOT NULL,
    comment_text VARCHAR2(500),
    actor_id NUMBER NOT NULL,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT fk_hist_comp FOREIGN KEY (complaint_id) REFERENCES complaints (id),
    CONSTRAINT fk_hist_actor FOREIGN KEY (actor_id) REFERENCES users (id)
);

CREATE TABLE comments (
    id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    complaint_id NUMBER NOT NULL,
    author_id NUMBER NOT NULL,
    body VARCHAR2(2000) NOT NULL,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT fk_cmt_comp FOREIGN KEY (complaint_id) REFERENCES complaints (id),
    CONSTRAINT fk_cmt_author FOREIGN KEY (author_id) REFERENCES users (id)
);

CREATE TABLE work_orders (
    id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    complaint_id NUMBER NOT NULL UNIQUE,
    assignee_id NUMBER NOT NULL,
    scheduled_at TIMESTAMP,
    status VARCHAR2(30) NOT NULL,
    notes VARCHAR2(1000),
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT fk_wo_comp FOREIGN KEY (complaint_id) REFERENCES complaints (id),
    CONSTRAINT fk_wo_assignee FOREIGN KEY (assignee_id) REFERENCES users (id)
);

