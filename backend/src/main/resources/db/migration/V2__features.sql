ALTER TABLE complaints ADD (version NUMBER DEFAULT 0 NOT NULL);

CREATE TABLE complaint_attachments (
    id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    complaint_id NUMBER NOT NULL,
    original_name VARCHAR2(255) NOT NULL,
    object_key VARCHAR2(500) NOT NULL,
    content_type VARCHAR2(120) NOT NULL,
    size_bytes NUMBER NOT NULL,
    uploaded_by NUMBER NOT NULL,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT fk_attachment_complaint FOREIGN KEY (complaint_id) REFERENCES complaints(id),
    CONSTRAINT fk_attachment_user FOREIGN KEY (uploaded_by) REFERENCES users(id)
);

CREATE TABLE notifications (
    id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id NUMBER NOT NULL,
    complaint_id NUMBER,
    message VARCHAR2(500) NOT NULL,
    read_at TIMESTAMP,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT fk_notification_user FOREIGN KEY (user_id) REFERENCES users(id),
    CONSTRAINT fk_notification_complaint FOREIGN KEY (complaint_id) REFERENCES complaints(id)
);

CREATE TABLE password_reset_tokens (
    id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id NUMBER NOT NULL,
    token_hash VARCHAR2(128) NOT NULL UNIQUE,
    expires_at TIMESTAMP NOT NULL,
    used_at TIMESTAMP,
    CONSTRAINT fk_reset_user FOREIGN KEY (user_id) REFERENCES users(id)
);

CREATE INDEX idx_complaints_created ON complaints(created_at);
CREATE INDEX idx_complaints_status ON complaints(status);
CREATE INDEX idx_notification_user ON notifications(user_id, read_at);
